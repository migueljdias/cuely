import { categories, recipes, tools } from "@/catalog";

const q = (v: unknown): string => {
  if (v === null || v === undefined) return "null";
  if (typeof v === "boolean") return v ? "true" : "false";
  if (typeof v === "number") return String(v);
  return `'${String(v).replace(/'/g, "''")}'`;
};
const j = (v: unknown) => `${q(JSON.stringify(v))}::jsonb`;

/** The seed as separate idempotent statements (for drivers that take one statement per query). */
export function generateSeedStatements(): string[] {
  const out: string[] = [];
  for (const c of categories) {
    out.push(
      `insert into categories (slug, name, description, how_to_choose, sort_order) values (${q(c.slug)}, ${q(c.name)}, ${q(c.description)}, ${q(c.howToChoose)}, ${c.order})\n  on conflict (slug) do update set name = excluded.name, description = excluded.description, how_to_choose = excluded.how_to_choose, sort_order = excluded.sort_order;`,
    );
  }
  for (const t of tools) {
    out.push(
      `insert into tools (slug, name, category, website, pricing_url, summary, pitch, best_for, watch_out, free_tier, paid_starts_at, free_tier_commercial_use, open_source, self_hostable, baseline, fit, cost, health, verified_on) values (${[
        q(t.slug), q(t.name), q(t.category), q(t.website), q(t.pricingUrl), q(t.summary), q(t.pitch), j(t.bestFor),
        j(t.watchOut), q(t.freeTier), q(t.paidStartsAt), q(t.freeTierCommercialUse), q(t.openSource),
        q(t.selfHostable), q(t.baseline), j(t.fit), t.cost ? j(t.cost) : "null", t.health ? j(t.health) : "null", q(t.verifiedOn),
      ].join(", ")})\n  on conflict (slug) do update set name = excluded.name, category = excluded.category, website = excluded.website, pricing_url = excluded.pricing_url, summary = excluded.summary, pitch = excluded.pitch, best_for = excluded.best_for, watch_out = excluded.watch_out, free_tier = excluded.free_tier, paid_starts_at = excluded.paid_starts_at, free_tier_commercial_use = excluded.free_tier_commercial_use, open_source = excluded.open_source, self_hostable = excluded.self_hostable, baseline = excluded.baseline, fit = excluded.fit, cost = excluded.cost, health = excluded.health, verified_on = excluded.verified_on, updated_at = now();`,
    );
  }
  for (const r of recipes) {
    out.push(
      `insert into recipes (slug, title, summary, body, verified_on) values (${q(r.slug)}, ${q(r.title)}, ${q(r.summary)}, ${j(r)}, ${q(r.verifiedOn)})\n  on conflict (slug) do update set title = excluded.title, summary = excluded.summary, body = excluded.body, verified_on = excluded.verified_on, updated_at = now();`,
    );
    out.push(`delete from recipe_tools where recipe_slug = ${q(r.slug)};`);
    for (const s of r.stack) {
      out.push(
        `insert into recipe_tools (recipe_slug, category, tool_slug, optional) values (${q(r.slug)}, ${q(s.category)}, ${q(s.tool)}, ${q(!!s.optional)});`,
      );
    }
  }
  return out;
}

/** Idempotent seed SQL generated from the TypeScript catalog. */
export function generateSeedSql(): string {
  return [
    "-- Generated by `npm run db:sql` from src/catalog. Do not edit by hand.",
    "begin;",
    ...generateSeedStatements(),
    "commit;",
    "",
  ].join("\n");
}

/** Splits db/schema.sql into statements (it has no semicolons inside comments or strings). */
export function splitSchema(schema: string): string[] {
  return schema
    .split("\n")
    .filter((l) => !l.trim().startsWith("--"))
    .join("\n")
    .split(";")
    .map((s) => s.trim())
    .filter(Boolean);
}
